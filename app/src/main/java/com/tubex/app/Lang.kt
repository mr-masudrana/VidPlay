import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import java.util.Locale

object L {
    var en by mutableStateOf(false)

    /** mode: 0 বাংলা, 1 English, 2 সিস্টেম */
    fun apply(mode: Int) {
        en = when (mode) {
            1 -> true
            2 -> Locale.getDefault().language != "bn"
            else -> false
        }
    }

    fun t(bn: String): String = if (en) EN[bn] ?: bn else bn

    fun f(bn: String, vararg args: Any?): String {
        var s = t(bn)
        for (i in args.indices) s = s.replace("{$i}", args[i].toString())
        return s
    }
}

